import assert from 'node:assert/strict';
import test from 'node:test';
import { Pool } from 'pg';
import { listSalespersonEarningSales, listSalespersonEarnings } from './salesperson-earnings.js';

test('Ganancias de vendedores suma la comisión real por vendedor y marca la comisión incompleta', {
  skip: !process.env.SALESPERSON_TEST_DATABASE_URL && 'define SALESPERSON_TEST_DATABASE_URL',
}, async () => {
  const db = new Pool({ connectionString: process.env.SALESPERSON_TEST_DATABASE_URL, max: 1 });
  try {
    await db.query(`begin;
      create temporary table "user" (
        id text, name text, email text, role text, active boolean default true, commission_percent numeric
      );
      create temporary table user_roles (user_id text, role text);
      create temporary table products (id int, commission_amount numeric, name text, main_sku text);
      create temporary table orders (
        id int, created_by text, currency text default 'PEN',
        order_status text default 'confirmed', payment_status text default 'paid',
        fulfillment_status text default 'delivered', total numeric,
        external_order_number text, customer jsonb default '{}',
        ordered_at timestamptz default '2026-10-15T15:00:00Z', created_at timestamptz default now()
      );
      create temporary table order_items (
        id int generated by default as identity, order_id int, product_id int, quantity numeric,
        commission_amount numeric, description text, sku text, main_sku text
      );
      insert into "user" (id, name, email, role, active, commission_percent) values
        ('ana', 'Ana', 'ana@x.pe', 'operator', true, 10),
        ('beto', 'Beto', 'beto@x.pe', 'vendedor', true, 0),
        ('carla', 'Carla', 'carla@x.pe', 'vendedor', false, 0),
        ('dani', 'Dani', 'dani@x.pe', 'vendedor', true, 3),
        ('admin', 'Admin', 'admin@x.pe', 'admin', true, 0);
      insert into user_roles values ('ana', 'vendedor'), ('admin', 'admin');
      insert into products values (1, 5, 'Manta', 'AG301'), (2, null, 'Bolso', 'HOG025'), (3, 0, 'Bebe', 'BB110');
      insert into orders (id, created_by, total, payment_status, fulfillment_status, currency, ordered_at, external_order_number) values
        (1, 'ana', 100, 'paid', 'delivered', 'PEN', '2026-10-15T15:00:00Z', 'VTA-1'),
        (2, 'ana', 200, 'pending', 'pending', 'PEN', '2026-10-16T15:00:00Z', 'VTA-2'),
        (3, 'beto', 150, 'paid', 'delivered', 'PEN', '2026-10-17T15:00:00Z', 'VTA-3'),
        (4, 'beto', 80, 'paid', 'delivered', 'PEN', '2026-10-18T15:00:00Z', 'VTA-4'),
        (5, 'ana', 999, 'paid', 'cancelled', 'PEN', '2026-10-19T15:00:00Z', 'VTA-5'),
        (6, 'ana', 500, 'paid', 'delivered', 'USD', '2026-10-20T15:00:00Z', 'VTA-6'),
        (7, 'admin', 300, 'paid', 'delivered', 'PEN', '2026-10-21T15:00:00Z', 'VTA-7'),
        (8, 'ana', 50, 'paid', 'delivered', 'PEN', '2026-10-01T03:00:00Z', 'VTA-8'),
        (9, 'beto', 60, 'paid', 'delivered', 'PEN', '2026-10-31T23:30:00-05:00', 'VTA-9'),
        (10, 'ana', 70, 'refunded', 'delivered', 'PEN', '2026-10-22T15:00:00Z', 'VTA-10');
      insert into order_items (order_id, product_id, quantity, commission_amount) values
        (1, 1, 2, null),
        (2, 2, 1, null),
        (3, 1, 1, null), (3, 2, 1, null),
        (4, 2, 1, null),
        (5, 1, 20, null),
        (6, 1, 1, null),
        (7, 1, 1, null),
        (8, 1, 1, null),
        (9, 3, 2, 4),
        (10, 1, 1, null);
    `);

    const report = await listSalespersonEarnings({ from: '2026-10-01', to: '2026-10-31' }, db);
    const byId = Object.fromEntries(report.salespeople.map((row) => [row.userId, row]));

    assert.deepEqual(Object.keys(byId).sort(), ['ana', 'beto', 'dani']);
    // Ana: catálogo (2 × 5) + % del vendedor sobre 200; excluye cancelado, reembolsado,
    // USD y el pedido que en Lima cae el 30 de septiembre.
    assert.equal(byId.ana.ordersCount, 2);
    assert.equal(byId.ana.salesTotal, 300);
    assert.equal(byId.ana.commission, 30);
    assert.equal(byId.ana.paidCommission, 10);
    assert.equal(byId.ana.percentOrders, 1);
    assert.equal(byId.ana.incompleteOrders, 0);
    assert.equal(byId.ana.otherCurrencyOrders, 1);
    assert.equal(byId.ana.commissionShare, 0.1);
    // Beto: línea sin comisión suma 0 (parcial), pedido sin ninguna comisión (0),
    // y la comisión corregida en la línea prevalece sobre el catálogo.
    assert.equal(byId.beto.ordersCount, 3);
    assert.equal(byId.beto.salesTotal, 290);
    assert.equal(byId.beto.commission, 13);
    assert.equal(byId.beto.incompleteOrders, 2);
    assert.equal(byId.beto.linesWithoutCommission, 2);
    assert.equal(byId.dani.ordersCount, 0);
    assert.equal(byId.dani.commissionShare, null);
    assert.equal(report.salespeople[0].userId, 'ana');

    assert.equal(report.totals.salesTotal, 590);
    assert.equal(report.totals.commission, 43);
    assert.equal(report.totals.incompleteOrders, 2);
    assert.equal(report.totals.withSales, 2);

    const page = await listSalespersonEarnings({ from: '2026-10-01', to: '2026-10-31', limit: 1, offset: 1 }, db);
    assert.equal(page.salespeople.length, 1);
    assert.equal(page.totalCount, 3);
    assert.equal(page.totals.commission, 43);

    const detail = await listSalespersonEarningSales('beto', { from: '2026-10-01', to: '2026-10-31' }, db);
    assert.deepEqual(
      detail.sales.map(({ orderNumber, commission, commissionRule, linesWithoutCommission }) => (
        { orderNumber, commission, commissionRule, linesWithoutCommission }
      )),
      [
        { orderNumber: 'VTA-9', commission: 8, commissionRule: 'catalog', linesWithoutCommission: 0 },
        { orderNumber: 'VTA-4', commission: 0, commissionRule: 'missing', linesWithoutCommission: 1 },
        { orderNumber: 'VTA-3', commission: 5, commissionRule: 'partial', linesWithoutCommission: 1 },
      ],
    );
    await assert.rejects(
      listSalespersonEarningSales('admin', { from: '2026-10-01', to: '2026-10-31' }, db),
      (error) => error.status === 404,
    );
  } finally {
    await db.query('rollback');
    await db.end();
  }
});
